import { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import api, { getErrorMessage } from '../api/client.js';
import Layout from '../components/Layout.jsx';
import StatCard from '../components/StatCard.jsx';
import { modeLabel, pluralize, toneForPercentage } from '../utils/format.js';

export default function Analytics() {
  const navigate = useNavigate();
  const [diagnostics, setDiagnostics] = useState(null);
  const [overview, setOverview] = useState(null);
  const [aiStatus, setAiStatus] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [starting, setStarting] = useState('');

  useEffect(() => {
    let cancelled = false;
    async function load() {
      setLoading(true);
      setError('');
      const results = await Promise.allSettled([
        api.get('/analytics/diagnostics'),
        api.get('/analytics/overview'),
        api.get('/ai/status'),
      ]);
      if (cancelled) return;
      const [diagnosticsResult, overviewResult, aiResult] = results;
      if (diagnosticsResult.status === 'fulfilled') setDiagnostics(diagnosticsResult.value.data);
      if (overviewResult.status === 'fulfilled') setOverview(overviewResult.value.data);
      if (aiResult.status === 'fulfilled') setAiStatus(aiResult.value.data);
      const firstFailure = results.find((result) => result.status === 'rejected');
      if (firstFailure) setError(getErrorMessage(firstFailure.reason));
      setLoading(false);
    }
    load();
    return () => {
      cancelled = true;
    };
  }, []);

  async function startRecommended(rec) {
    if (!rec.assessmentId) return;
    setError('');
    setStarting(rec.assessmentId);
    try {
      const response = await api.post('/exams/start', { assessmentId: rec.assessmentId });
      const session = response.data.session;
      navigate(
        session.status === 'in_progress' ? `/exam/${session.id}` : `/result/${session.id}`
      );
    } catch (err) {
      const activeId = err.response?.data?.details?.activeSessionId;
      if (err.response?.data?.code === 'ACTIVE_SESSION' && activeId) {
        navigate(`/exam/${activeId}`);
        return;
      }
      setError(getErrorMessage(err));
      setStarting('');
    }
  }

  const topics = diagnostics?.topics || [];
  const weakTopics = diagnostics?.weakTopics || [];
  const strongTopics = diagnostics?.strongTopics || [];
  const recommendations = diagnostics?.recommendations || [];
  const trend = overview?.trend || [];
  const stats = overview?.stats;

  return (
    <Layout>
      <div className="dashboard-head">
        <div>
          <span className="eyebrow">Weakness diagnostics</span>
          <h1>Weakness diagnostics</h1>
          <p className="page-lede">
            Failure logs are mapped to syllabus nodes, then translated into a focused study plan.
          </p>
        </div>
        <span className="pill pill-soft">Diagnostic engine</span>
      </div>

      {error ? <div className="alert alert-error">{error}</div> : null}

      {loading ? (
        <div className="skeleton-block skeleton-diagnostics" />
      ) : (
        <>
          <section
            className={`diagnostic-narrative ${
              diagnostics?.narrativeSource === 'llm' ? 'narrative-llm' : ''
            }`}
          >
            <span className="ai-note-mark">AI</span>
            <div>
              <div className="narrative-head">
                <strong>Your personalised diagnostic</strong>
                <span className="pill pill-soft">
                  {diagnostics?.narrativeSource === 'llm'
                    ? 'Generated by LLM'
                    : 'Generated by local engine'}
                </span>
              </div>
              <p>{diagnostics?.narrative}</p>
              <span className="narrative-foot">
                Based on {pluralize(diagnostics?.attemptsAnalyzed || 0, 'graded session')} and{' '}
                {pluralize(topics.length, 'syllabus node')}.
              </span>
            </div>
          </section>

          <div className="stat-grid stat-grid-four">
            <StatCard
              label="Sessions analysed"
              value={diagnostics?.attemptsAnalyzed ?? 0}
              hint="Graded attempts in the last 25 sessions"
              tone="blue"
            />
            <StatCard
              label="Weak nodes"
              value={weakTopics.length}
              hint="Below 60% mastery"
              tone="red"
            />
            <StatCard
              label="Strong nodes"
              value={strongTopics.length}
              hint="At or above 75% mastery"
              tone="green"
            />
            <StatCard
              label="Latest average"
              value={`${stats?.averagePercentage ?? 0}%`}
              hint="Across all graded work"
              tone={toneForPercentage(stats?.averagePercentage)}
            />
          </div>

          <div className="analytics-grid">
            <section className="dashboard-section">
              <div className="panel-heading">
                <div>
                  <span className="eyebrow">Recommended next steps</span>
                  <h2>Targeted practice tracks</h2>
                </div>
              </div>
              {recommendations.length ? (
                <div className="recommendation-list">
                  {recommendations.map((rec) => (
                    <article className="recommendation-card" key={rec.topicKey}>
                      <div className="recommendation-main">
                        <span className={`mini-score tone-${toneForPercentage(rec.accuracy)}`}>
                          {rec.accuracy}%
                        </span>
                        <div>
                          <strong>{rec.topic}</strong>
                          <span>
                            {rec.courseCode} · {rec.courseTitle}
                          </span>
                          <p>{rec.action}</p>
                        </div>
                      </div>
                      <div className="recommendation-actions">
                        {rec.assessmentId ? (
                          <button
                            type="button"
                            className="btn btn-primary btn-sm"
                            onClick={() => startRecommended(rec)}
                            disabled={Boolean(starting)}
                          >
                            {starting === rec.assessmentId ? 'Starting…' : 'Start recommended practice'}
                          </button>
                        ) : null}
                        {rec.courseId ? (
                          <button
                            type="button"
                            className="btn btn-outline btn-sm"
                            onClick={() => navigate(`/courses/${rec.courseId}`)}
                          >
                            Open module
                          </button>
                        ) : null}
                      </div>
                    </article>
                  ))}
                </div>
              ) : (
                <div className="empty-inline">
                  No weak nodes detected yet. Complete more graded sessions to unlock targeted
                  recommendations.
                </div>
              )}
            </section>

            <section className="dashboard-section">
              <div className="panel-heading">
                <div>
                  <span className="eyebrow">Progress trend</span>
                  <h2>Recent assessment scores</h2>
                </div>
              </div>
              {trend.length ? (
                <div className="trend-chart">
                  {trend.map((point) => (
                    <div className="trend-col" key={point.id}>
                      <span className="trend-value">{point.percentage}%</span>
                      <div className="trend-track">
                        <i
                          className={`tone-${toneForPercentage(point.percentage)}`}
                          style={{ height: `${Math.max(6, point.percentage)}%` }}
                        />
                      </div>
                      <span className="trend-label">{point.label}</span>
                    </div>
                  ))}
                </div>
              ) : (
                <div className="empty-inline">No graded attempts to chart yet.</div>
              )}
              {stats ? (
                <div className="trend-footer">
                  <span>Best {stats.bestPercentage}%</span>
                  <span>Pass rate {stats.passRate}%</span>
                  <span>Study time {stats.studyMinutes} min</span>
                </div>
              ) : null}
            </section>
          </div>

          <section className="dashboard-section">
            <div className="panel-heading">
              <div>
                <span className="eyebrow">Mastery map</span>
                <h2>Every syllabus node analysed</h2>
              </div>
              <span className="muted">Sorted weakest first</span>
            </div>
            {topics.length ? (
              <div className="mastery-list">
                {topics.map((topic) => (
                  <div className="mastery-row" key={topic.key}>
                    <div className="mastery-main">
                      <strong>{topic.title}</strong>
                      <span>
                        {topic.courseCode} · {pluralize(topic.questions, 'question')}
                      </span>
                    </div>
                    <div className="mastery-bar">
                      <i
                        className={`tone-${toneForPercentage(topic.percentage)}`}
                        style={{ width: `${Math.max(4, topic.percentage)}%` }}
                      />
                    </div>
                    <span className={`mastery-score tone-text-${toneForPercentage(topic.percentage)}`}>
                      {topic.percentage}%
                    </span>
                  </div>
                ))}
              </div>
            ) : (
              <div className="empty-state">
                <h3>No diagnostic data yet</h3>
                <p>Finish a practice or mock session to build your mastery map.</p>
              </div>
            )}
          </section>

          {strongTopics.length ? (
            <section className="dashboard-section">
              <div className="panel-heading">
                <div>
                  <span className="eyebrow">Strengths</span>
                  <h2>Nodes you have mastered</h2>
                </div>
              </div>
              <div className="strong-grid">
                {strongTopics.map((topic) => (
                  <div className="strong-card" key={topic.key}>
                    <span className="pill pill-green">{topic.percentage}%</span>
                    <strong>{topic.title}</strong>
                    <span className="cell-sub">
                      {topic.courseCode} · {pluralize(topic.questions, 'question')}
                    </span>
                  </div>
                ))}
              </div>
            </section>
          ) : null}

          {overview?.recentAttempts?.length ? (
            <section className="dashboard-section">
              <div className="panel-heading">
                <div>
                  <span className="eyebrow">Session archive</span>
                  <h2>Latest graded sessions</h2>
                </div>
              </div>
              <div className="history-list">
                {overview.recentAttempts.slice(0, 5).map((attempt) => (
                  <button
                    type="button"
                    className="history-row"
                    key={attempt.id}
                    onClick={() => navigate(`/result/${attempt.id}`)}
                  >
                    <div className="history-main">
                      <strong>
                        {attempt.courseCode} · {attempt.assessmentTitle}
                      </strong>
                      <span>{modeLabel(attempt.mode)}</span>
                    </div>
                    <span className={`score-chip tone-${toneForPercentage(attempt.percentage)}`}>
                      {attempt.percentage}%
                    </span>
                  </button>
                ))}
              </div>
            </section>
          ) : null}
        </>
      )}
    </Layout>
  );
}
